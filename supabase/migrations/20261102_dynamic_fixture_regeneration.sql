create table if not exists public.fixture_pending_assignments (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  event_team_id bigint not null references public.event_teams(id) on delete cascade,
  team_id bigint not null references public.teams(id),
  group_id bigint null references public.event_groups(id) on delete cascade,
  round_number integer not null check (round_number >= 1),
  status text not null default 'pending' check (status in ('pending', 'resolved', 'cancelled')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz null,
  unique (event_team_id, round_number)
);

create index if not exists fixture_pending_assignments_event_round_idx
on public.fixture_pending_assignments (event_id, round_number, status);

grant select, insert, update on public.fixture_pending_assignments to authenticated;
grant usage, select on sequence public.fixture_pending_assignments_id_seq to authenticated;

create or replace function public.create_fixture_pending_assignments(
  p_event_id bigint,
  p_expected_last_started_round integer,
  p_team_start_updates jsonb,
  p_assignments jsonb
)
returns integer
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  actual_last_started_round integer;
  requested_team_count integer;
  updated_team_count integer;
  assignment_count integer;
begin
  if jsonb_typeof(p_team_start_updates) <> 'array' or jsonb_typeof(p_assignments) <> 'array' then
    raise exception 'Pending fixture data must be JSON arrays.';
  end if;

  perform et.id from public.event_teams et where et.event_id = p_event_id for update;
  perform m.id
  from public.matches m
  where m.event_id = p_event_id and (m.stage_type = 'league' or m.stage_type is null)
  for share;

  select coalesce(max(m.round_number), 0)
  into actual_last_started_round
  from public.matches m
  where m.event_id = p_event_id
    and (m.stage_type = 'league' or m.stage_type is null)
    and m.status is distinct from 'cancelled'
    and (m.status in ('played', 'in_progress') or m.score1 is not null or m.score2 is not null);

  if actual_last_started_round <> p_expected_last_started_round then
    raise exception 'The last started round changed after the preview. Reload it and try again.';
  end if;

  requested_team_count := jsonb_array_length(p_team_start_updates);
  update public.event_teams et
  set fixture_start_round = team_update.to_round
  from jsonb_to_recordset(p_team_start_updates) as team_update(
    event_team_id bigint,
    from_round integer,
    to_round integer
  )
  where et.id = team_update.event_team_id
    and et.event_id = p_event_id
    and et.fixture_start_round = team_update.from_round;
  get diagnostics updated_team_count = row_count;

  if updated_team_count <> requested_team_count then
    raise exception 'Team participation changed after the preview. Reload it and try again.';
  end if;

  insert into public.fixture_pending_assignments (
    event_id, event_team_id, team_id, group_id, round_number, status, resolved_at
  )
  select
    p_event_id,
    assignment.event_team_id,
    assignment.team_id,
    assignment.group_id,
    assignment.round_number,
    'pending',
    null
  from jsonb_to_recordset(p_assignments) as assignment(
    event_team_id bigint,
    team_id bigint,
    group_id bigint,
    round_number integer
  )
  join public.event_teams et
    on et.id = assignment.event_team_id
    and et.event_id = p_event_id
    and et.team_id = assignment.team_id
    and et.status = 'active'
  where assignment.round_number >= et.fixture_start_round
  on conflict (event_team_id, round_number) do update
  set status = 'pending', group_id = excluded.group_id, resolved_at = null;

  get diagnostics assignment_count = row_count;
  if assignment_count <> jsonb_array_length(p_assignments) then
    raise exception 'One or more pending assignments are invalid.';
  end if;

  return assignment_count;
end
$$;

revoke all on function public.create_fixture_pending_assignments(bigint, integer, jsonb, jsonb) from public;
grant execute on function public.create_fixture_pending_assignments(bigint, integer, jsonb, jsonb) to authenticated;
grant execute on function public.create_fixture_pending_assignments(bigint, integer, jsonb, jsonb) to service_role;

create or replace function public.resolve_fixture_pending_assignments(
  p_event_id bigint,
  p_round_number integer,
  p_pending_ids bigint[],
  p_match_updates jsonb,
  p_matches jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  pending_count integer;
  updated_match_count integer;
  inserted_match_count integer;
  next_pos integer;
  next_num integer;
begin
  perform m.id
  from public.matches m
  where m.event_id = p_event_id
    and (m.stage_type = 'league' or m.stage_type is null)
    and m.round_number = p_round_number
  for update;

  if exists (
    select 1 from public.matches m
    where m.event_id = p_event_id
      and (m.stage_type = 'league' or m.stage_type is null)
      and m.round_number = p_round_number
      and m.status is distinct from 'cancelled'
      and (m.status in ('played', 'in_progress') or m.score1 is not null or m.score2 is not null)
  ) then
    raise exception 'This round has already started and its pending teams cannot be assigned.';
  end if;

  perform pending.id
  from public.fixture_pending_assignments pending
  where pending.id = any(coalesce(p_pending_ids, array[]::bigint[]))
    and pending.event_id = p_event_id
    and pending.round_number = p_round_number
    and pending.status = 'pending'
  for update;

  select count(*) into pending_count
  from public.fixture_pending_assignments pending
  where pending.id = any(coalesce(p_pending_ids, array[]::bigint[]))
    and pending.event_id = p_event_id
    and pending.round_number = p_round_number
    and pending.status = 'pending';

  if pending_count <> cardinality(coalesce(p_pending_ids, array[]::bigint[])) then
    raise exception 'Pending assignments changed. Reload the round and try again.';
  end if;

  update public.matches m
  set
    team1_id = case when m.team1_id = change.from_team_id then change.to_team_id else m.team1_id end,
    team2_id = case when m.team2_id = change.from_team_id then change.to_team_id else m.team2_id end
  from jsonb_to_recordset(p_match_updates) as change(
    match_id bigint,
    from_team_id bigint,
    to_team_id bigint
  )
  where m.id = change.match_id
    and m.event_id = p_event_id
    and m.round_number = p_round_number
    and m.status = 'scheduled'
    and (m.team1_id = change.from_team_id or m.team2_id = change.from_team_id);
  get diagnostics updated_match_count = row_count;

  if updated_match_count <> jsonb_array_length(p_match_updates) then
    raise exception 'A scheduled match changed while pending teams were assigned.';
  end if;

  select coalesce(max(m.pos), 0) + 1, coalesce(max(m.num), 0) + 1
  into next_pos, next_num
  from public.matches m where m.event_id = p_event_id;

  insert into public.matches (
    event_id, pos, num, team1_id, team2_id, group_id, round_id, round_number,
    status, date, time, field_id, field_number, stage_type, is_extra
  )
  select
    p_event_id,
    next_pos + row_number() over () - 1,
    next_num + row_number() over () - 1,
    planned.team1_id,
    planned.team2_id,
    planned.group_id,
    null,
    p_round_number,
    'scheduled',
    planned.match_date,
    planned.match_time,
    planned.field_id,
    planned.field_number,
    'league',
    false
  from jsonb_to_recordset(p_matches) as planned(
    team1_id bigint,
    team2_id bigint,
    group_id bigint,
    match_date date,
    match_time time,
    field_id bigint,
    field_number integer
  );
  get diagnostics inserted_match_count = row_count;

  if inserted_match_count <> jsonb_array_length(p_matches) then
    raise exception 'An unexpected number of pending matches was created.';
  end if;

  update public.fixture_pending_assignments
  set status = 'resolved', resolved_at = now()
  where id = any(coalesce(p_pending_ids, array[]::bigint[]));

  return jsonb_build_object(
    'updated_match_count', updated_match_count,
    'inserted_match_count', inserted_match_count,
    'resolved_assignment_count', pending_count
  );
end
$$;

revoke all on function public.resolve_fixture_pending_assignments(bigint, integer, bigint[], jsonb, jsonb) from public;
grant execute on function public.resolve_fixture_pending_assignments(bigint, integer, bigint[], jsonb, jsonb) to authenticated;
grant execute on function public.resolve_fixture_pending_assignments(bigint, integer, bigint[], jsonb, jsonb) to service_role;

create or replace function public.apply_fixture_regeneration(
  p_event_id bigint,
  p_start_round integer,
  p_expected_match_ids bigint[],
  p_team_start_updates jsonb,
  p_matches jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  current_match_ids bigint[];
  expected_match_ids bigint[];
  cancelled_count integer;
  inserted_count integer;
  updated_team_count integer;
  requested_team_count integer;
  requested_match_count integer;
  next_pos integer;
  next_num integer;
begin
  if p_start_round is null or p_start_round < 1 then
    raise exception 'The fixture start round must be a positive integer.';
  end if;

  if p_team_start_updates is null or jsonb_typeof(p_team_start_updates) <> 'array' then
    raise exception 'Team start updates must be a JSON array.';
  end if;

  if p_matches is null or jsonb_typeof(p_matches) <> 'array' then
    raise exception 'Planned matches must be a JSON array.';
  end if;

  perform e.id from public.events e where e.id = p_event_id for share;
  if not found then
    raise exception 'Event % was not found.', p_event_id;
  end if;

  perform et.id
  from public.event_teams et
  where et.event_id = p_event_id
  for update;

  perform m.id
  from public.matches m
  where m.event_id = p_event_id
    and (m.stage_type = 'league' or m.stage_type is null)
  for update;

  if exists (
    select 1
    from public.matches m
    where m.event_id = p_event_id
      and (m.stage_type = 'league' or m.stage_type is null)
      and m.status is distinct from 'cancelled'
      and m.round_number >= p_start_round
      and (
        m.status in ('played', 'in_progress')
        or m.score1 is not null
        or m.score2 is not null
      )
  ) then
    raise exception 'A round included in the preview has started. Reload the fixture and try again.';
  end if;

  select coalesce(array_agg(m.id order by m.id), array[]::bigint[])
  into current_match_ids
  from public.matches m
  where m.event_id = p_event_id
    and (m.stage_type = 'league' or m.stage_type is null)
    and not coalesce(m.is_extra, false)
    and m.status = 'scheduled'
    and m.score1 is null
    and m.score2 is null
    and m.round_number >= p_start_round;

  select coalesce(array_agg(match_id order by match_id), array[]::bigint[])
  into expected_match_ids
  from unnest(coalesce(p_expected_match_ids, array[]::bigint[])) match_id;

  if current_match_ids is distinct from expected_match_ids then
    raise exception 'The scheduled fixture changed after the preview. Reload it and try again.';
  end if;

  requested_team_count := jsonb_array_length(p_team_start_updates);
  if (
    select count(*)
    from jsonb_to_recordset(p_team_start_updates) as team_update(
      event_team_id bigint,
      from_round integer,
      to_round integer
    )
  ) <> requested_team_count then
    raise exception 'One or more team start updates are malformed.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_team_start_updates) as team_update(
      event_team_id bigint,
      from_round integer,
      to_round integer
    )
    where team_update.event_team_id is null
      or team_update.from_round is null
      or team_update.to_round is null
      or team_update.to_round < p_start_round
  ) then
    raise exception 'A team start update contains an invalid round.';
  end if;

  update public.event_teams et
  set fixture_start_round = team_update.to_round
  from jsonb_to_recordset(p_team_start_updates) as team_update(
    event_team_id bigint,
    from_round integer,
    to_round integer
  )
  where et.id = team_update.event_team_id
    and et.event_id = p_event_id
    and et.fixture_start_round = team_update.from_round;

  get diagnostics updated_team_count = row_count;
  if updated_team_count <> requested_team_count then
    raise exception 'Team participation changed after the preview. Reload it and try again.';
  end if;

  requested_match_count := jsonb_array_length(p_matches);
  if (
    select count(*)
    from jsonb_to_recordset(p_matches) as planned(
      team1_id bigint,
      team2_id bigint,
      group_id bigint,
      round_number integer,
      match_date date,
      match_time time,
      field_id bigint,
      field_number integer
    )
  ) <> requested_match_count then
    raise exception 'One or more planned matches are malformed.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_matches) as planned(
      team1_id bigint,
      team2_id bigint,
      group_id bigint,
      round_number integer,
      match_date date,
      match_time time,
      field_id bigint,
      field_number integer
    )
    where planned.team1_id is null
      or planned.team2_id is null
      or planned.team1_id = planned.team2_id
      or planned.round_number < p_start_round
      or not exists (
        select 1 from public.event_teams et
        where et.event_id = p_event_id
          and et.team_id = planned.team1_id
          and et.status = 'active'
          and et.fixture_start_round <= planned.round_number
      )
      or not exists (
        select 1 from public.event_teams et
        where et.event_id = p_event_id
          and et.team_id = planned.team2_id
          and et.status = 'active'
          and et.fixture_start_round <= planned.round_number
      )
  ) then
    raise exception 'The planned fixture contains an ineligible team or invalid round.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_matches) as planned(
      team1_id bigint,
      team2_id bigint,
      group_id bigint,
      round_number integer,
      match_date date,
      match_time time,
      field_id bigint,
      field_number integer
    )
    cross join lateral (values (planned.team1_id), (planned.team2_id)) participant(team_id)
    group by planned.round_number, planned.group_id, participant.team_id
    having count(*) > 1
  ) then
    raise exception 'A team cannot be scheduled more than once in the same round and group.';
  end if;

  update public.matches m
  set status = 'cancelled'
  where m.event_id = p_event_id
    and (m.stage_type = 'league' or m.stage_type is null)
    and not coalesce(m.is_extra, false)
    and m.status = 'scheduled'
    and m.score1 is null
    and m.score2 is null
    and m.round_number >= p_start_round;

  get diagnostics cancelled_count = row_count;

  select coalesce(max(m.pos), 0) + 1, coalesce(max(m.num), 0) + 1
  into next_pos, next_num
  from public.matches m
  where m.event_id = p_event_id;

  insert into public.matches (
    event_id,
    pos,
    num,
    team1_id,
    team2_id,
    group_id,
    round_id,
    round_number,
    status,
    date,
    time,
    field_id,
    field_number,
    stage_type,
    is_extra
  )
  select
    p_event_id,
    next_pos + row_number() over (order by planned.round_number, planned.group_id nulls first) - 1,
    next_num + row_number() over (order by planned.round_number, planned.group_id nulls first) - 1,
    planned.team1_id,
    planned.team2_id,
    planned.group_id,
    null,
    planned.round_number,
    'scheduled',
    planned.match_date,
    planned.match_time,
    planned.field_id,
    planned.field_number,
    'league',
    false
  from jsonb_to_recordset(p_matches) as planned(
    team1_id bigint,
    team2_id bigint,
    group_id bigint,
    round_number integer,
    match_date date,
    match_time time,
    field_id bigint,
    field_number integer
  );

  get diagnostics inserted_count = row_count;
  if inserted_count <> requested_match_count then
    raise exception 'Atomic fixture regeneration inserted an unexpected number of matches.';
  end if;

  return jsonb_build_object(
    'cancelled_match_count', cancelled_count,
    'inserted_match_count', inserted_count,
    'updated_team_count', updated_team_count
  );
end
$$;

revoke all on function public.apply_fixture_regeneration(bigint, integer, bigint[], jsonb, jsonb) from public;
grant execute on function public.apply_fixture_regeneration(bigint, integer, bigint[], jsonb, jsonb) to authenticated;
grant execute on function public.apply_fixture_regeneration(bigint, integer, bigint[], jsonb, jsonb) to service_role;
